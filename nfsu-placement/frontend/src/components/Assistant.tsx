import { FormEvent, KeyboardEvent, useEffect, useRef, useState } from "react";
import { Link } from "react-router-dom";
import { api, errorLines } from "../lib/api";
import { useAuth } from "../lib/auth";
import { OFFER_TYPES, when } from "../lib/format";
import { Icon } from "./icons";
import RichText from "./RichText";
import { Reasons, Verdict } from "./ui";

interface Source { id: string; title: string; provenance: string; company?: string | null; domain?: string; difficulty?: string;
  source_title?: string; source_url?: string; path?: string }
interface DriveRow { id: number; company: string; title: string; offer_type: string; package: string; closes: string;
  decision: "ALLOW" | "FLAG" | "BLOCK"; reasons: { severity: string; message: string }[]; application_status: string | null }
interface Reply { answer: string; intent: string; mode: string; status: string; sources: Source[]; drives: DriveRow[]; suggestions: string[] }
interface Msg { id: number; from: "you" | "uj"; text: string; reply?: Reply; error?: boolean }

const MODE: Record<string, string> = {
  policy_engine: "Policy engine · your record", student_record: "Your record", placement_data: "Live placement data",
  question_bank: "Question bank", gemini: "Gemini, grounded in the question bank",
  gemini_open: "AI-generated by Gemini · not from the reviewed question bank", help: "Assistant", sign_in: "Sign-in needed", refused: "Assistant", meta: "About U.J.",
  read_only: "Read-only: U.J. cannot act for you",
};
const PROVENANCE: Record<string, string> = { official: "Official source", reported: "Reported experience", practice: "Practice question" };
const START_PUBLIC = ["How does placement work at NFSU?", "Explain the category rules", "Show this session's placement statistics", "Cybersecurity interview questions"];
const START_STUDENT = ["Which open drives can I apply to?", "What is my placement status?", "When do my offers expire?", "Cybersecurity interview questions"];

let nextId = 1;

/** U.J., the placement assistant. Read-only: it explains and checks, and the dashboards do the acting.
 *  Signed-in users ask through /assistant (students get answers about their own record); everyone else
 *  through /public/assistant. The conversation lives only in memory and is cleared when the user changes. */
export default function Assistant() {
  const { me } = useAuth();
  const [open, setOpen] = useState(false);
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [text, setText] = useState("");
  const [busy, setBusy] = useState(false);
  const listRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);
  const launcherRef = useRef<HTMLButtonElement>(null);
  const student = me?.role === "student";

  useEffect(() => { setMsgs([]); }, [me?.username]);  // never show one user's answers to the next
  useEffect(() => { if (open) inputRef.current?.focus(); }, [open]);
  useEffect(() => { listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: "smooth" }); }, [msgs, busy]);

  const close = () => { setOpen(false); launcherRef.current?.focus(); };

  const send = async (q: string) => {
    const question = q.trim();
    if (!question || busy) return;
    setText("");
    setMsgs((m) => [...m, { id: nextId++, from: "you", text: question }]);
    setBusy(true);
    try {
      const reply = await api<Reply>(me ? "/assistant" : "/public/assistant", { body: { message: question } });
      setMsgs((m) => [...m, { id: nextId++, from: "uj", text: reply.answer, reply }]);
    } catch (e) {
      setMsgs((m) => [...m, { id: nextId++, from: "uj", text: errorLines(e).join(" "), error: true }]);
    } finally {
      setBusy(false);
    }
  };
  const submit = (e: FormEvent) => { e.preventDefault(); send(text); };
  const onKey = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); send(text); }
  };
  const last = [...msgs].reverse().find((m) => m.reply)?.reply;
  const chips = last?.suggestions ?? (student ? START_STUDENT : START_PUBLIC);

  return (
    <>
      <button ref={launcherRef} className={`uj-launcher${open ? " hidden" : ""}`} onClick={() => setOpen(true)} aria-expanded={open} aria-controls="uj-panel">
        <span className="uj-launcher-icon"><Icon name="sparkle" /></span>
        <span className="uj-launcher-text"><strong>Ask U.J.</strong><small>Placement assistant</small></span>
      </button>

      {open && (
        <section id="uj-panel" className="uj-panel" role="dialog" aria-label="U.J. placement assistant" onKeyDown={(e) => e.key === "Escape" && close()}>
          <header className="uj-head">
            <img src="/images/nfsu-logo.png" alt="" className="uj-logo" />
            <div className="uj-title">
              <strong>U.J. · Placement assistant</strong>
              <small>{student ? "Answers from your own record and the placement policy" : "Answers from NFSU placement data and a reviewed question bank"}</small>
            </div>
            <button className="uj-close" onClick={close} aria-label="Close the assistant"><span aria-hidden="true">×</span></button>
          </header>

          <div className="uj-list" ref={listRef} aria-live="polite">
            {msgs.length === 0 && (
              <div className="uj-msg uj">
                <div className="uj-bubble">
                  <RichText text={`Hello${me ? `, ${me.name.split(" ")[0]}` : ""}. I am **U.J.**, the NFSU placement assistant.\n`
                    + (student ? "- Ask about your status, your offers or which open drives you can apply to\n" : "- Sign in as a student to ask about your own placement\n")
                    + "- Ask how placement works, the category rules or this session's statistics\n- Practise interview questions by topic or company\n"
                    + "I only read information. Applying and accepting stay on your dashboard."} />
                </div>
              </div>
            )}
            {msgs.map((m) => (
              <div key={m.id} className={`uj-msg ${m.from}`}>
                <div className={`uj-bubble${m.error ? " uj-error" : ""}`}>
                  {m.reply && <span className={`uj-mode${m.reply.mode === "gemini_open" ? " uj-mode-ai" : ""}`}><Icon name={m.reply.intent === "personal" ? "scale" : m.reply.intent === "prep" ? "graduation" : "chart"} />{MODE[m.reply.mode] ?? m.reply.mode}</span>}
                  {m.from === "you" ? <p>{m.text}</p> : <RichText text={m.text} />}
                  {m.reply?.status === "sign_in_required" && <Link className="btn btn-sm" to="/login" onClick={close}><Icon name="login" />Sign in</Link>}
                  {!!m.reply?.drives.length && (
                    <ul className="uj-drives">
                      {m.reply.drives.map((d) => (
                        <li key={d.id}>
                          <div className="uj-drive-head">
                            <span><strong>{d.company}</strong> · {d.title}</span>
                            <Verdict decision={d.decision} />
                          </div>
                          <span className="fine">{OFFER_TYPES[d.offer_type]} · {d.package} · closes {when(d.closes)}{d.application_status && ` · your application: ${d.application_status}`}</span>
                          <Reasons reasons={d.reasons} />
                        </li>
                      ))}
                      <li className="uj-drive-cta"><Link to="/student" onClick={close}>Open My placement to apply <Icon name="arrowRight" /></Link></li>
                    </ul>
                  )}
                  {!!m.reply?.sources.length && (
                    <div className="uj-sources">
                      <span className="fine">Sources</span>
                      {m.reply.sources.map((s) => (
                        <span key={s.id} className={`uj-source prov-${s.provenance}`}>
                          <b>{PROVENANCE[s.provenance] ?? s.provenance}</b>
                          {s.path ? <Link to={s.path} onClick={close}>{s.title}</Link>
                            : s.source_url?.startsWith("https://") ? <a href={s.source_url} target="_blank" rel="noopener noreferrer">{s.title}</a>
                            : <span>{s.title}</span>}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              </div>
            ))}
            {busy && <div className="uj-msg uj"><div className="uj-bubble uj-typing" aria-label="U.J. is answering"><i /><i /><i /></div></div>}
          </div>

          <div className="uj-chips">
            {chips.map((c) => <button key={c} type="button" onClick={() => send(c)} disabled={busy}>{c}</button>)}
          </div>
          <form className="uj-input" onSubmit={submit}>
            <textarea ref={inputRef} value={text} onChange={(e) => setText(e.target.value)} onKeyDown={onKey} rows={1} maxLength={1000}
              placeholder={student ? "Ask about your drives, offers or interview prep" : "Ask about placement or interview prep"} aria-label="Your question" />
            <button className="btn" disabled={busy || !text.trim()} aria-label="Send"><Icon name="arrowRight" /></button>
          </form>
          <p className="uj-note">Questions are not stored. Interview-prep questions may be sent to Google Gemini; answers about you come only from your own record and never go to Gemini.</p>
        </section>
      )}
    </>
  );
}
